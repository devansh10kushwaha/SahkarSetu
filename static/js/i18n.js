let LANG = localStorage.getItem("ss_lang") || "hi";
function t(key){ return (I18N[key] && I18N[key][LANG]) || key; }
function applyI18n(){
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const v = I18N[el.dataset.i18n];
    if(v) el.innerHTML = v[LANG];
  });
  document.getElementById("lang-hi").classList.toggle("on", LANG==="hi");
  document.getElementById("lang-en").classList.toggle("on", LANG==="en");
  const urBtn = document.getElementById("lang-ur");
  if(urBtn) urBtn.classList.toggle("on", LANG==="ur");
  applyDirection();
}
function applyDirection(){
  document.documentElement.lang = LANG;
  document.documentElement.dir = (LANG === "ur") ? "rtl" : "ltr";
}
function setLang(l){
  LANG = l; localStorage.setItem("ss_lang", l);
  applyI18n();
  if(window.rerender) rerender();
}
